package me.towdium.jecalculation.utils.wrappers;

public class Quad<T, U, V, W> {
    public T one;
    public U two;
    public V three;
    public W four;

    public Quad(T one, U two, V three, W four) {
        this.one = one;
        this.two = two;
        this.three = three;
        this.four = four;
    }
}
